"""
Render the generated files and write them to the output directory (OUTPT-01..05).

dbt-s-layer owns the top-level `exp__*.sql`, `sem__*.sql` and `_semantic_views.yml`
files of the output directory, and only when their first line is its header.
Everything else there is the user's and is never touched.
"""

from __future__ import annotations

import io
import os
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

from ruamel.yaml import YAML

from dbt_s_layer.errors import OutputConflictError
from dbt_s_layer.exports import render_exports

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping

    from dbt_s_layer.exports import ExportModel
    from dbt_s_layer.project import SemanticProject

SCHEMA_FILE = "_semantic_views.yml"
MODEL_PREFIXES = ("exp__", "sem__")
_DO_NOT_EDIT = "Do not edit: change the semantic YAML and run `dbt-s-layer generate`."
_SQL_MARK = "-- Generated by dbt-s-layer"
_YAML_MARK = "# Generated by dbt-s-layer"
_STAGING_PREFIX = ".dbt-s-layer-"


@dataclass(frozen=True)
class OutputDiff:
    """How the output directory differs from the generated files, by file name."""

    # On disk with other content.
    changed: tuple[str, ...]
    # Generated but not on disk.
    missing: tuple[str, ...]
    # Owned files on disk that are no longer generated.
    stale: tuple[str, ...]

    @property
    def clean(self) -> bool:
        """Whether the directory already matches."""
        return not (self.changed or self.missing or self.stale)


# --- render -------------------------------------------------------------------


def is_owned_name(name: str) -> bool:
    """Whether a top-level file name is one dbt-s-layer generates."""
    return name == SCHEMA_FILE or (name.startswith(MODEL_PREFIXES) and name.endswith(".sql"))


def _export_header(model: ExportModel) -> str:
    return (
        f"{_SQL_MARK} from saved query {model.saved_query!r} (export {model.export!r}). "
        f"{_DO_NOT_EDIT}\n"
    )


def _schema_file(models: Iterable[ExportModel], descriptions: Mapping[str, str | None]) -> str:
    entries = [
        {
            "name": model.file_name.removesuffix(".sql"),
            "description": descriptions.get(model.saved_query)
            or f"Export {model.export!r} of saved query {model.saved_query!r}.",
        }
        for model in models
    ]
    yaml = YAML()
    yaml.indent(mapping=2, sequence=4, offset=2)
    yaml.width = 4096  # never fold a description
    yaml.allow_unicode = True
    stream = io.StringIO()
    yaml.dump({"version": 2, "models": entries}, stream)  # pyright: ignore[reportUnknownMemberType]
    return f"{_YAML_MARK}. {_DO_NOT_EDIT}\n{stream.getvalue()}"


def render_output(project: SemanticProject, *, adapter: str | None = None) -> dict[str, str]:
    """Return every generated file as name -> text, sorted; empty when nothing is generated."""
    models = render_exports(project, adapter=adapter)
    if not models:
        return {}
    descriptions = {sq.name: sq.description for sq in project.semantic_manifest.saved_queries}
    files = {model.file_name: _export_header(model) + model.body for model in models}
    files[SCHEMA_FILE] = _schema_file(models, descriptions)
    return dict(sorted(files.items()))


# --- disk ---------------------------------------------------------------------


def _is_generated(path: Path) -> bool:
    mark = _YAML_MARK if path.name == SCHEMA_FILE else _SQL_MARK
    try:
        with path.open("rb") as handle:
            first = handle.readline()
    except OSError:
        return False
    return first.decode("utf-8", errors="replace").startswith(mark)


def _owned_on_disk(output_dir: Path) -> dict[str, bytes]:
    """Read the owned files already in `output_dir`; refuse any dbt-s-layer did not write."""
    if not output_dir.exists():
        return {}
    if not output_dir.is_dir():
        raise OutputConflictError(f"output directory {output_dir} is not a directory.")
    owned: dict[str, bytes] = {}
    for path in sorted(output_dir.iterdir()):
        if not (path.is_file() and is_owned_name(path.name)):
            continue
        if not _is_generated(path):
            raise OutputConflictError(
                f"{path} is not generated by dbt-s-layer (its first line is not the "
                "dbt-s-layer header), so it will not be overwritten. Rename or move it: "
                f"dbt-s-layer owns {', '.join(p + '*.sql' for p in MODEL_PREFIXES)} and "
                f"{SCHEMA_FILE} in this directory."
            )
        owned[path.name] = path.read_bytes()
    return owned


def _diff(files: Mapping[str, str], on_disk: Mapping[str, bytes]) -> OutputDiff:
    return OutputDiff(
        changed=tuple(
            n for n, t in files.items() if n in on_disk and on_disk[n] != t.encode("utf-8")
        ),
        missing=tuple(n for n in files if n not in on_disk),
        stale=tuple(n for n in sorted(on_disk) if n not in files),
    )


def diff_output(files: Mapping[str, str], output_dir: Path) -> OutputDiff:
    """Compare `files` with `output_dir` without writing anything."""
    return _diff(files, _owned_on_disk(output_dir))


def apply_output(files: Mapping[str, str], output_dir: Path) -> OutputDiff:
    """
    Make `output_dir` match `files` and return what changed.

    New and changed files are written to a staging directory beside `output_dir`
    first, so a failure while writing leaves `output_dir` as it was; each is then
    moved into place with `os.replace`, and stale owned files are deleted.
    Unchanged files are not rewritten.
    """
    diff = diff_output(files, output_dir)
    if diff.clean:
        return diff
    output_dir.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=_STAGING_PREFIX, dir=output_dir.parent))
    try:
        to_write = [*diff.changed, *diff.missing]
        for name in to_write:
            (staging / name).write_bytes(files[name].encode("utf-8"))
        for name in sorted(to_write):
            os.replace(staging / name, output_dir / name)
        for name in diff.stale:
            (output_dir / name).unlink()
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return diff
