"""
Render the generated files and write them to the output directory (OUTPT-01..05).

dbt-s-layer owns the top-level `exp__*.sql`, `sem__*.sql` and `_semantic_views.yml`
files of the output directory, and only when their first line is its header.
Everything else there is the user's and is never touched.
"""

from __future__ import annotations

import io
import os
import shutil
import tempfile
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, cast

from ruamel.yaml import YAML

from dbt_s_layer._project_yaml import read_dbt_project
from dbt_s_layer.errors import ModelClashError, OutputConflictError
from dbt_s_layer.exports import render_exports
from dbt_s_layer.s_layer import read_s_layer_blocks
from dbt_s_layer.semantic_views import render_semantic_views

if TYPE_CHECKING:
    from collections.abc import Iterable, Iterator

    from dbt_s_layer.artifacts import ModelNode
    from dbt_s_layer.exports import ExportModel
    from dbt_s_layer.project import SemanticProject
    from dbt_s_layer.semantic_views import SemanticViewModel

SCHEMA_FILE = "_semantic_views.yml"
MODEL_PREFIXES = ("exp__", "sem__")
_DO_NOT_EDIT = "Do not edit: change the semantic YAML and run `dbt-s-layer generate`."
_SQL_MARK = "-- Generated by dbt-s-layer"
_YAML_MARK = "# Generated by dbt-s-layer"
_STAGING_PREFIX = ".dbt-s-layer-"


class RenderedOutput(Mapping[str, str]):
    """Every generated file as name -> text, sorted, plus warnings worth showing the user."""

    def __init__(self, files: Mapping[str, str], warnings: Iterable[str] = ()) -> None:
        self._files = dict(sorted(files.items()))
        self.warnings: tuple[str, ...] = tuple(warnings)

    def __getitem__(self, name: str) -> str:
        return self._files[name]

    def __iter__(self) -> Iterator[str]:
        return iter(self._files)

    def __len__(self) -> int:
        return len(self._files)

    def __repr__(self) -> str:
        return f"RenderedOutput({self._files!r}, warnings={self.warnings!r})"


@dataclass(frozen=True)
class OutputDiff:
    """How the output directory differs from the generated files, by file name."""

    # On disk with other content.
    changed: tuple[str, ...]
    # Generated but not on disk.
    missing: tuple[str, ...]
    # Owned files on disk that are no longer generated.
    stale: tuple[str, ...]

    @property
    def clean(self) -> bool:
        """Whether the directory already matches."""
        return not (self.changed or self.missing or self.stale)


# --- render -------------------------------------------------------------------


def is_owned_name(name: str) -> bool:
    """Whether a top-level file name is one dbt-s-layer generates."""
    return name == SCHEMA_FILE or (name.startswith(MODEL_PREFIXES) and name.endswith(".sql"))


def _export_header(model: ExportModel) -> str:
    return (
        f"{_SQL_MARK} from saved query {model.saved_query!r} (export {model.export!r}). "
        f"{_DO_NOT_EDIT}\n"
    )


def _semantic_header(model: SemanticViewModel) -> str:
    mark = _YAML_MARK if model.comment_prefix == "#" else _SQL_MARK
    return f"{mark} from semantic model {model.semantic_model!r}. {_DO_NOT_EDIT}\n"


def _schema_file(
    models: Iterable[ExportModel],
    descriptions: Mapping[str, str | None],
    views: Iterable[SemanticViewModel] = (),
) -> str:
    entries = [
        {
            "name": model.file_name.removesuffix(".sql"),
            "description": descriptions.get(model.saved_query)
            or f"Export {model.export!r} of saved query {model.saved_query!r}.",
        }
        for model in models
    ]
    entries += [
        {
            "name": view.file_name.removesuffix(".sql"),
            "description": view.description
            or f"Semantic view of semantic model {view.semantic_model!r}.",
        }
        for view in views
    ]
    entries.sort(key=lambda entry: entry["name"])
    yaml = YAML()
    yaml.indent(mapping=2, sequence=4, offset=2)
    yaml.width = 4096  # never fold a description
    yaml.allow_unicode = True
    stream = io.StringIO()
    yaml.dump({"version": 2, "models": entries}, stream)  # pyright: ignore[reportUnknownMemberType]
    return f"{_YAML_MARK}. {_DO_NOT_EDIT}\n{stream.getvalue()}"


def _relation_key(schema: str | None, alias: str) -> tuple[str | None, str]:
    return (schema.lower() if schema is not None else None, alias.lower())


# A folder-level schema dbt-s-layer cannot resolve (Jinja).
_UNKNOWN = object()


def project_model_paths(project_dir: Path) -> list[Path]:
    """The project's `model-paths`, resolved."""
    value = read_dbt_project(project_dir).get("model-paths")
    paths = [str(p) for p in cast("list[object]", value)] if isinstance(value, list) else []
    return [(project_dir / p).resolve() for p in paths or ["models"]]


def _as_mapping(value: object) -> dict[str, object]:
    if not isinstance(value, dict):
        return {}
    return {str(k): v for k, v in cast("dict[object, object]", value).items()}


def _folder_schema(project: SemanticProject, output_dir: Path) -> object:
    """
    The `+schema` dbt_project.yml gives models in `output_dir`: a str, None, or _UNKNOWN.

    Exports without a schema of their own leave it out of `config()`, so dbt
    applies the folder's. The deepest setting wins, as in dbt.
    """
    root = project.dbt_manifest.metadata.project_name
    levels = [_as_mapping(read_dbt_project(project.project_dir).get("models"))]
    levels.append(_as_mapping(levels[0].get(root)))
    for model_path in project_model_paths(project.project_dir):
        if output_dir.is_relative_to(model_path):
            for part in output_dir.relative_to(model_path).parts:
                levels.append(_as_mapping(levels[-1].get(part)))
            break
    schema: object = None
    for level in levels:
        for key in ("schema", "+schema"):
            if key in level:
                schema = level[key]
    if schema is None:
        return None
    if not isinstance(schema, str) or "{{" in schema or "{%" in schema:
        return _UNKNOWN
    return schema


@dataclass(frozen=True)
class _Generated:
    """What the clash check needs from a generated model of either kind."""

    file_name: str
    alias: str
    # Its own custom schema, or None for the output folder's.
    schema: str | None
    # e.g. "export 'x' of saved query 'y'"
    label: str
    # How the user can move it out of the way.
    remedy: str


def _generated(
    exports: Iterable[ExportModel], views: Iterable[SemanticViewModel]
) -> list[_Generated]:
    models = [
        _Generated(
            file_name=m.file_name,
            alias=m.alias,
            schema=m.schema,
            label=f"export {m.export!r} of saved query {m.saved_query!r}",
            remedy="Give the export its own `alias` or `schema`.",
        )
        for m in exports
    ]
    models += [
        _Generated(
            file_name=v.file_name,
            alias=v.alias,
            schema=v.schema,
            label=f"semantic view of semantic model {v.semantic_model!r}",
            remedy="Rename the other model, or give the output directory its own `+schema`.",
        )
        for v in views
    ]
    return models


def _where(schema: str | None) -> str:
    return f"custom schema {schema.lower()!r}" if schema else "the target schema"


def _check_clashes(
    project: SemanticProject,
    exports: Iterable[ExportModel],
    output_dir: Path,
    views: Iterable[SemanticViewModel] = (),
) -> None:
    """
    Refuse generated models that clash with the user's own nodes, or with each other.

    dbt-s-layer's own files in `output_dir` are earlier output and are skipped. A
    relation is compared by custom schema and alias, case-insensitively, which
    is exact whenever generate_schema_name depends only on the custom schema
    (03-RESEARCH finding 3). A model without its own schema takes the output
    directory's folder `+schema`; if that is templated, the model is not
    compared with user nodes. Nodes that set a database, and ephemeral models,
    are skipped: generated models cannot set a database, and ephemeral models
    build no relation. Semantic views are also compared with exports (exports
    with each other are checked by `render_exports`).
    """
    root = project.dbt_manifest.metadata.project_name
    output_dir = output_dir.resolve()
    by_name: dict[str, ModelNode] = {}
    by_relation: dict[tuple[str | None, str], ModelNode] = {}
    for node in sorted(project.dbt_manifest.nodes.values(), key=lambda n: n.unique_id):
        if node.package_name == root:
            path = project.project_dir / node.original_file_path
            if path.parent.resolve() == output_dir and is_owned_name(path.name):
                continue
            by_name.setdefault(node.name.lower(), node)
        if (
            node.config.database is not None
            or node.config.target_schema is not None
            or node.config.materialized == "ephemeral"
        ):
            continue
        by_relation.setdefault(_relation_key(node.config.schema_name, node.alias), node)

    folder_schema = _folder_schema(project, output_dir)
    models = _generated(exports, views)
    for model in models:
        name = model.file_name.removesuffix(".sql")
        node = by_name.get(name.lower())
        if node is not None:
            raise ModelClashError(
                f"{model.file_name} would define model {name!r}, but {node.unique_id} "
                f"({node.original_file_path}) already has that name. Rename one of them."
            )
        schema = model.schema if model.schema is not None else folder_schema
        if schema is _UNKNOWN:
            continue
        schema = cast("str | None", schema)
        node = by_relation.get(_relation_key(schema, model.alias))
        if node is not None:
            raise ModelClashError(
                f"{model.label} and {node.unique_id} ({node.original_file_path}) would both "
                f"build alias {model.alias!r} in {_where(schema)}. {model.remedy}"
            )

    # A templated folder schema is unknown, but every model in the folder shares it.
    seen: dict[tuple[str | None, str], _Generated] = {}
    for model in models:
        schema = model.schema if model.schema is not None else folder_schema
        if schema is _UNKNOWN:
            key, where = ("\0folder", model.alias.lower()), "the output directory's schema"
        else:
            schema = cast("str | None", schema)
            key, where = _relation_key(schema, model.alias), _where(schema)
        other = seen.get(key)
        if other is not None:
            raise ModelClashError(
                f"{other.label} and {model.label} would both build alias {model.alias!r} in "
                f"{where}. {other.remedy}"
            )
        seen[key] = model


def render_output(
    project: SemanticProject, *, adapter: str | None = None, output_dir: Path | None = None
) -> RenderedOutput:
    """
    Return every generated file as name -> text, sorted; empty when nothing is generated.

    Exports for every adapter metricflow renders, and semantic views for the
    adapters dbt-s-layer has a renderer for. With `output_dir`, also refuse models
    that clash with the project's own. The result's `warnings` lists what the
    user should know: features left out of semantic views, a missing package.
    """
    # A bad block stops every adapter, even one with no semantic view renderer yet.
    read_s_layer_blocks(project)
    exports = render_exports(project, adapter=adapter)
    adapter = adapter or project.dbt_manifest.metadata.adapter_type
    # render_exports has already refused a missing adapter.
    views = render_semantic_views(project, adapter=cast("str", adapter))
    if output_dir is not None:
        _check_clashes(project, exports, output_dir, views.models)
    if not exports and not views.models:
        return RenderedOutput({}, views.warnings)
    descriptions = {sq.name: sq.description for sq in project.semantic_manifest.saved_queries}
    files = {model.file_name: _export_header(model) + model.body for model in exports}
    for view in views.models:
        if view.file_name in files:
            raise ModelClashError(f"{view.file_name} would be generated twice.")
        files[view.file_name] = _semantic_header(view) + view.body
    files[SCHEMA_FILE] = _schema_file(exports, descriptions, views.models)
    return RenderedOutput(files, views.warnings)


# --- disk ---------------------------------------------------------------------


def _is_generated(path: Path) -> bool:
    if path.name == SCHEMA_FILE:
        marks: tuple[str, ...] = (_YAML_MARK,)
    elif path.name.startswith("sem__"):
        # A Databricks metric view's body is YAML, so its header is a YAML comment.
        marks = (_SQL_MARK, _YAML_MARK)
    else:
        marks = (_SQL_MARK,)
    try:
        with path.open("rb") as handle:
            first = handle.readline()
    except OSError:
        return False
    return first.decode("utf-8", errors="replace").startswith(marks)


def _owned_on_disk(output_dir: Path) -> dict[str, bytes]:
    """Read the owned files already in `output_dir`; refuse any dbt-s-layer did not write."""
    if not output_dir.exists():
        return {}
    if not output_dir.is_dir():
        raise OutputConflictError(f"output directory {output_dir} is not a directory.")
    owned: dict[str, bytes] = {}
    for path in sorted(output_dir.iterdir()):
        if not (path.is_file() and is_owned_name(path.name)):
            continue
        if not _is_generated(path):
            raise OutputConflictError(
                f"{path} is not generated by dbt-s-layer (its first line is not the "
                "dbt-s-layer header), so it will not be overwritten. Rename or move it: "
                f"dbt-s-layer owns {', '.join(p + '*.sql' for p in MODEL_PREFIXES)} and "
                f"{SCHEMA_FILE} in this directory."
            )
        owned[path.name] = path.read_bytes()
    return owned


def _diff(files: Mapping[str, str], on_disk: Mapping[str, bytes]) -> OutputDiff:
    return OutputDiff(
        changed=tuple(
            n for n, t in files.items() if n in on_disk and on_disk[n] != t.encode("utf-8")
        ),
        missing=tuple(n for n in files if n not in on_disk),
        stale=tuple(n for n in sorted(on_disk) if n not in files),
    )


def diff_output(files: Mapping[str, str], output_dir: Path) -> OutputDiff:
    """Compare `files` with `output_dir` without writing anything."""
    return _diff(files, _owned_on_disk(output_dir))


def apply_output(files: Mapping[str, str], output_dir: Path) -> OutputDiff:
    """
    Make `output_dir` match `files` and return what changed.

    New and changed files are written to a staging directory beside `output_dir`
    first. Then each old file is moved aside into the staging directory and the
    new one moved into place with `os.replace`, and stale owned files are moved
    aside too. If any step fails, every move is undone, so `output_dir` is left
    as it was. Unchanged files are not rewritten.
    """
    diff = diff_output(files, output_dir)
    if diff.clean:
        return diff
    created = not output_dir.exists()
    output_dir.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=_STAGING_PREFIX, dir=output_dir.parent))
    aside = staging / "replaced"
    # (name, old file moved aside, new file moved in), in the order done.
    moves: list[tuple[str, bool, bool]] = []
    try:
        aside.mkdir()
        to_write = sorted([*diff.changed, *diff.missing])
        for name in to_write:
            (staging / name).write_bytes(files[name].encode("utf-8"))
        try:
            for name in to_write:
                had_old = name in diff.changed
                if had_old:
                    os.replace(output_dir / name, aside / name)
                    moves.append((name, True, False))
                os.replace(staging / name, output_dir / name)
                if had_old:
                    moves[-1] = (name, True, True)
                else:
                    moves.append((name, False, True))
            for name in diff.stale:
                os.replace(output_dir / name, aside / name)
                moves.append((name, True, False))
        except BaseException:
            _undo(moves, output_dir, aside)
            if created and not any(output_dir.iterdir()):
                output_dir.rmdir()
            raise
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return diff


def _undo(moves: list[tuple[str, bool, bool]], output_dir: Path, aside: Path) -> None:
    for name, had_old, moved_in in reversed(moves):
        if moved_in:
            (output_dir / name).unlink()
        if had_old:
            os.replace(aside / name, output_dir / name)
