def test_failure_while_staging_changes_nothing(
    make_project: MakeProject, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    apply_output(files, out)
    (out / "README.md").write_text("mine\n")
    before = _snapshot(out)
    changed = {name: text + "-- v2\n" for name, text in files.items()}

    real = Path.write_bytes
    calls: list[Path] = []

    def flaky(self: Path, data: bytes) -> int:
        calls.append(self)
        if len(calls) == 3:
            raise OSError("disk full")
        return real(self, data)

    monkeypatch.setattr(Path, "write_bytes", flaky)
    with pytest.raises(OSError, match="disk full"):
        apply_output(changed, out)
    assert _snapshot(out) == before
    assert len(calls) == 3
    # The staging directory is cleaned up.
    assert sorted(p.name for p in tmp_path.iterdir()) == ["core_export", "out"]


def test_files_reach_place_by_os_replace(
    make_project: MakeProject, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    replaced: list[tuple[str, str]] = []
    real = os.replace

    def spy(src: str | os.PathLike[str], dst: str | os.PathLike[str]) -> None:
        replaced.append((Path(src).parent.name, Path(dst).name))
        real(src, dst)

    monkeypatch.setattr(output.os, "replace", spy)
    apply_output(files, out)
    assert sorted(dst for _, dst in replaced) == sorted(files)
    # Staged next to the output directory, so on the same filesystem.
    assert all(src.startswith(".dbt-s-layer-") for src, _ in replaced)


