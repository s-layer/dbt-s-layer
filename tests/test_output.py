def _semantic(project_dir: Path, mutate: Callable[[dict[str, Any]], None]) -> None:
    path = project_dir / "target" / "semantic_manifest.json"
    raw: dict[str, Any] = json.loads(path.read_text())
    mutate(raw)
    path.write_text(json.dumps(raw))


def _files(make_project: MakeProject, set_name: str = "core_export") -> RenderedOutput:
    return render_output(load_project(make_project(set_name)))


def _snapshot(directory: Path) -> dict[str, tuple[bytes, int]]:
    """Every path under `directory` with its content (files) and mtime."""
    snapshot: dict[str, tuple[bytes, int]] = {}
    for path in sorted(directory.rglob("*")):
        content = path.read_bytes() if path.is_file() else b""
        snapshot[str(path.relative_to(directory))] = (content, path.stat().st_mtime_ns)
    return snapshot


