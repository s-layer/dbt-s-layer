REVENUE_BY_DAY_HEADER = (
    "-- Generated by dbt-s-layer from saved query 'revenue_by_day' (export "
    "'exp_revenue_by_day'). Do not edit: change the semantic YAML and run "
    "`dbt-s-layer generate`.\n"
)

SCHEMA_YAML = """\
# Generated by dbt-s-layer. Do not edit: change the semantic YAML and run `dbt-s-layer generate`.
version: 2
models:
  - name: exp__cumulative_revenue__exp_cumulative
    description: Export 'exp_cumulative' of saved query 'cumulative_revenue'.
  - name: exp__items_by_country__exp_items_by_country
    description: Export 'exp_items_by_country' of saved query 'items_by_country'.
  - name: exp__revenue_by_day__exp_revenue_by_day
    description: Export 'exp_revenue_by_day' of saved query 'revenue_by_day'.
  - name: exp__revenue_by_day__exp_revenue_by_day_view
    description: Export 'exp_revenue_by_day_view' of saved query 'revenue_by_day'.
  - name: exp__revenue_by_region_country__exp_region_country
    description: Export 'exp_region_country' of saved query 'revenue_by_region_country'.
"""


def _semantic(project_dir: Path, mutate: Callable[[dict[str, Any]], None]) -> None:
    path = project_dir / "target" / "semantic_manifest.json"
    raw: dict[str, Any] = json.loads(path.read_text())
    mutate(raw)
    path.write_text(json.dumps(raw))


def _files(make_project: MakeProject, set_name: str = "core_export") -> dict[str, str]:
    return render_output(load_project(make_project(set_name)))


def _snapshot(directory: Path) -> dict[str, tuple[bytes, int]]:
    """Every path under `directory` with its content (files) and mtime."""
    snapshot: dict[str, tuple[bytes, int]] = {}
    for path in sorted(directory.rglob("*")):
        content = path.read_bytes() if path.is_file() else b""
        snapshot[str(path.relative_to(directory))] = (content, path.stat().st_mtime_ns)
    return snapshot


# --- render -------------------------------------------------------------------


@pytest.mark.parametrize("set_name", EXPORT_SETS)
def test_renders_every_export_and_the_schema_file(set_name: str, make_project: MakeProject) -> None:
    files = _files(make_project, set_name)
    assert list(files) == [SCHEMA_FILE, *EXPORT_FILES]


def test_sql_files_start_with_the_header(make_project: MakeProject) -> None:
    files = _files(make_project)
    body = files["exp__revenue_by_day__exp_revenue_by_day.sql"]
    assert body.startswith(REVENUE_BY_DAY_HEADER + "{{ config(materialized='table'")
    for name in EXPORT_FILES:
        assert files[name].startswith("-- Generated by dbt-s-layer from saved query '")


def test_schema_file(make_project: MakeProject) -> None:
    assert _files(make_project)[SCHEMA_FILE] == SCHEMA_YAML


@pytest.mark.parametrize(
    "description",
    [
        "Daily revenue.",
        "Revenue: by day, 'paid' only # not a comment",
        "{{ doc('revenue_by_day') }}",
        "Multi\nline ünïcode",
    ],
)
def test_saved_query_description_round_trips(description: str, make_project: MakeProject) -> None:
    project_dir = make_project("core_export")

    def describe(raw: dict[str, Any]) -> None:
        sq = next(q for q in raw["saved_queries"] if q["name"] == "revenue_by_day")
        sq["description"] = description

    _semantic(project_dir, describe)
    text = render_output(load_project(project_dir))[SCHEMA_FILE]
    data: Any = YAML(typ="safe", pure=True).load(text)  # pyright: ignore[reportUnknownMemberType]
    descriptions = {m["name"]: m["description"] for m in data["models"]}
    assert descriptions["exp__revenue_by_day__exp_revenue_by_day"] == description
    assert descriptions["exp__revenue_by_day__exp_revenue_by_day_view"] == description


def test_no_exports_means_no_files(make_project: MakeProject) -> None:
    project_dir = make_project("core_export")

    def drop(raw: dict[str, Any]) -> None:
        for sq in raw["saved_queries"]:
            sq["exports"] = []

    _semantic(project_dir, drop)
    assert render_output(load_project(project_dir)) == {}


@pytest.mark.parametrize("set_name", EXPORT_SETS)
def test_rendering_is_byte_stable(set_name: str, make_project: MakeProject) -> None:
    project = load_project(make_project(set_name))
    first, second = render_output(project), render_output(project)
    assert first == second
    for text in first.values():
        assert "\r" not in text
        assert text.endswith("\n")
        assert not text.endswith("\n\n")


def test_adapter_is_passed_through(make_project: MakeProject) -> None:
    project = load_project(make_project("core_export"))
    duckdb = render_output(project)
    bigquery = render_output(project, adapter="bigquery")
    assert duckdb[SCHEMA_FILE] == bigquery[SCHEMA_FILE]
    assert duckdb != bigquery


# --- apply --------------------------------------------------------------------


def test_apply_creates_the_directory(make_project: MakeProject, tmp_path: Path) -> None:
    files = _files(make_project)
    out = tmp_path / "proj" / "models" / "semantic"
    result = apply_output(files, out)
    assert result == OutputDiff(changed=(), missing=tuple(files), stale=())
    assert {p.name: p.read_text() for p in out.iterdir()} == files
    assert sorted(p.name for p in out.parent.iterdir()) == ["semantic"]


def test_files_are_written_byte_for_byte(make_project: MakeProject, tmp_path: Path) -> None:
    files = _files(make_project)
    apply_output(files, tmp_path / "out")
    for name, text in files.items():
        assert (tmp_path / "out" / name).read_bytes() == text.encode("utf-8")


def test_second_apply_rewrites_nothing(make_project: MakeProject, tmp_path: Path) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    apply_output(files, out)
    before = _snapshot(out)
    assert apply_output(files, out) == OutputDiff(changed=(), missing=(), stale=())
    assert _snapshot(out) == before


def test_only_changed_files_are_rewritten(make_project: MakeProject, tmp_path: Path) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    apply_output(files, out)
    before = _snapshot(out)
    name = EXPORT_FILES[0]
    edited = {**files, name: files[name] + "-- changed\n"}
    assert apply_output(edited, out) == OutputDiff(changed=(name,), missing=(), stale=())
    after = _snapshot(out)
    assert after[name] != before[name]
    assert {k: v for k, v in after.items() if k != name} == {
        k: v for k, v in before.items() if k != name
    }


def test_stale_owned_files_are_removed(make_project: MakeProject, tmp_path: Path) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    apply_output(files, out)
    gone = EXPORT_FILES[0]
    remaining = {k: v for k, v in files.items() if k != gone}
    assert apply_output(remaining, out) == OutputDiff(changed=(), missing=(), stale=(gone,))
    assert not (out / gone).exists()


def test_everything_is_removed_when_nothing_is_generated(
    make_project: MakeProject, tmp_path: Path
) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    apply_output(files, out)
    (out / "README.md").write_text("mine\n")
    assert apply_output({}, out) == OutputDiff(changed=(), missing=(), stale=tuple(files))
    assert [p.name for p in out.iterdir()] == ["README.md"]


def test_other_files_are_left_alone(make_project: MakeProject, tmp_path: Path) -> None:
    out = tmp_path / "out"
    (out / "nested").mkdir(parents=True)
    keep = {
        "README.md": "mine\n",
        "notes.sql": "select 1\n",
        "exp__notes.txt": "not sql\n",
        "nested/exp__x__y.sql": "select 2\n",
        "_other.yml": "version: 2\n",
    }
    for name, text in keep.items():
        (out / name).write_text(text)
    apply_output(_files(make_project), out)
    for name, text in keep.items():
        assert (out / name).read_text() == text


@pytest.mark.parametrize("name", ["exp__mine__x.sql", "sem__orders.sql", SCHEMA_FILE])
def test_hand_written_owned_file_is_refused(
    name: str, make_project: MakeProject, tmp_path: Path
) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    out.mkdir()
    (out / name).write_text("select 1 -- mine\n")
    before = _snapshot(out)
    with pytest.raises(OutputConflictError, match=rf"{name}.*not generated by dbt-s-layer"):
        apply_output(files, out)
    assert _snapshot(out) == before
    assert sorted(p.name for p in tmp_path.iterdir()) == ["core_export", "out"]


def test_hand_edited_header_line_is_refused(make_project: MakeProject, tmp_path: Path) -> None:
    # Only the first line marks a file as generated.
    files = _files(make_project)
    out = tmp_path / "out"
    out.mkdir()
    (out / EXPORT_FILES[0]).write_text("select 1\n" + files[EXPORT_FILES[0]])
    with pytest.raises(OutputConflictError, match=EXPORT_FILES[0]):
        apply_output(files, out)


def test_failure_while_staging_changes_nothing(
    make_project: MakeProject, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    apply_output(files, out)
    (out / "README.md").write_text("mine\n")
    before = _snapshot(out)
    changed = {name: text + "-- v2\n" for name, text in files.items()}

    real = Path.write_bytes
    calls: list[Path] = []

    def flaky(self: Path, data: bytes) -> int:
        calls.append(self)
        if len(calls) == 3:
            raise OSError("disk full")
        return real(self, data)

    monkeypatch.setattr(Path, "write_bytes", flaky)
    with pytest.raises(OSError, match="disk full"):
        apply_output(changed, out)
    assert _snapshot(out) == before
    assert len(calls) == 3
    # The staging directory is cleaned up.
    assert sorted(p.name for p in tmp_path.iterdir()) == ["core_export", "out"]


def test_files_reach_place_by_os_replace(
    make_project: MakeProject, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    replaced: list[tuple[str, str]] = []
    real = os.replace

    def spy(src: str | os.PathLike[str], dst: str | os.PathLike[str]) -> None:
        replaced.append((Path(src).parent.name, Path(dst).name))
        real(src, dst)

    monkeypatch.setattr(output.os, "replace", spy)
    apply_output(files, out)
    assert sorted(dst for _, dst in replaced) == sorted(files)
    # Staged next to the output directory, so on the same filesystem.
    assert all(src.startswith(".dbt-s-layer-") for src, _ in replaced)


