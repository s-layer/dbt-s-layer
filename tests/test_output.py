def test_diff_of_a_fresh_directory(make_project: MakeProject, tmp_path: Path) -> None:
    files = _files(make_project)
    result = diff_output(files, tmp_path / "missing")
    assert result == OutputDiff(changed=(), missing=tuple(files), stale=())
    assert not result.clean
    assert not (tmp_path / "missing").exists()


def test_diff_after_apply_is_clean(make_project: MakeProject, tmp_path: Path) -> None:
    files = _files(make_project)
    apply_output(files, tmp_path / "out")
    result = diff_output(files, tmp_path / "out")
    assert result.clean
    assert result == OutputDiff(changed=(), missing=(), stale=())


def test_diff_reports_each_kind_and_writes_nothing(
    make_project: MakeProject, tmp_path: Path
) -> None:
    files = _files(make_project)
    out = tmp_path / "out"
    apply_output(files, out)
    a, b, c = EXPORT_FILES[:3]
    (out / a).write_text((out / a).read_text() + "-- hand edit\n")
    (out / b).unlink()
    stale = "exp__old__gone.sql"
    (out / stale).write_text(files[c])
    before = _snapshot(out)
    assert diff_output(files, out) == OutputDiff(changed=(a,), missing=(b,), stale=(stale,))
    assert _snapshot(out) == before


